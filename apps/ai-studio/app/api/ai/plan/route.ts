import { NextRequest, NextResponse } from 'next/server';
import { ThinkingLevel, Type } from '@google/genai';
import { z } from 'zod';
import { getGeminiClient, normalizeGeminiError, withGeminiRetry, requireGeminiSession } from '@/lib/server/gemini';
import { checkRateLimit } from '@/lib/security';
import { resolveSupportedModel } from '@/lib/models';
import { validateMissionPlan, type PlannedStepInput } from '@/lib/mission-logic';

const PlanSchema = z.object({
  objective: z.string().min(3).max(4000),
  model: z.string().max(64).optional(),
});

export async function POST(req: NextRequest) {
  try {
    const session = await requireGeminiSession(req);
    const rate = checkRateLimit(`ai-plan:${session.uid}`, 20, 60_000);
    if (!rate.allowed) {
      return NextResponse.json({ error: 'Rate limit exceeded.' }, { status: 429 });
    }

    const body = await req.json();
    const parsed = PlanSchema.safeParse(body);
    if (!parsed.success) {
      return NextResponse.json({ error: 'Objective must be 3-4000 characters.' }, { status: 400 });
    }

    const { objective, model } = parsed.data;
    const activeModel = resolveSupportedModel(model);
    const ai = getGeminiClient();

    const response = await withGeminiRetry(async () => {
      return ai.models.generateContent({
        model: activeModel,
        contents: `Create a practical multi-agent execution plan for this mission objective: "${objective}"`,
        config: {
          systemInstruction: `You are ORION, Mission Orchestrator for Google Agentic Browser.
Assign steps using only these lowercase agent IDs:
- "rover": research, fact-gathering, permitted web/search analysis
- "atlas": comparison, ranking, trade-off evaluation
- "aegis": security, policy, prompt-injection & approval check
- "mercury": simulated budget/procurement proposal (include whenever the objective involves buying, subscribing, pricing selection, or spending)
- "chronicle": compiling and saving the final mission report (always include as final step; if saving to Google Drive or sending email is implied, mark requiresApproval=true)
Keep plans focused (3 to 6 steps).`,
          ...(activeModel === 'gemini-4-hydrogen'
            ? { thinkingConfig: { thinkingLevel: ThinkingLevel.MEDIUM } }
            : {}),
          responseMimeType: 'application/json',
          responseSchema: {
            type: Type.OBJECT,
            required: ['title', 'planSummary', 'steps'],
            properties: {
              title: { type: Type.STRING, description: 'Short 3-8 word mission title.' },
              planSummary: { type: Type.STRING, description: '1-2 sentence orchestration summary.' },
              steps: {
                type: Type.ARRAY,
                items: {
                  type: Type.OBJECT,
                  required: ['agentId', 'title', 'instruction', 'requiresApproval'],
                  properties: {
                    agentId: {
                      type: Type.STRING,
                      enum: ['rover', 'atlas', 'aegis', 'mercury', 'chronicle'],
                      description: 'Must be one of: rover, atlas, aegis, mercury, chronicle',
                    },
                    title: { type: Type.STRING },
                    instruction: { type: Type.STRING },
                    requiresApproval: { type: Type.BOOLEAN },
                  },
                },
              },
            },
          },
        },
      });
    });

    const raw = JSON.parse((response.text ?? '{}').trim()) as {
      title?: string;
      planSummary?: string;
      steps?: PlannedStepInput[];
    };

    const validation = validateMissionPlan(raw.steps ?? []);
    if (!validation.valid) {
      return NextResponse.json(
        { error: validation.reason || 'Generated plan failed validation.' },
        { status: 422 }
      );
    }

    return NextResponse.json({
      title: (raw.title || objective).slice(0, 120),
      planSummary: (raw.planSummary || 'Multi-agent plan generated by Orion.').slice(0, 600),
      steps: validation.sanitizedSteps,
      model: activeModel,
    });
  } catch (err) {
    const normalized = normalizeGeminiError(err);
    return NextResponse.json(
      { error: normalized.message, code: normalized.code },
      { status: normalized.status }
    );
  }
}
